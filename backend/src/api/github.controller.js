import { Octokit } from "@octokit/rest";
import { PrismaClient } from "@prisma/client";
import { Buffer } from "buffer";
import slugify from "slugify";

const prisma = new PrismaClient();

// Helper to upload one file
async function uploadFile(octokit, owner, repo, filePath, content, commitMsg) {
  await octokit.repos.createOrUpdateFileContents({
    owner,
    repo,
    path: filePath,
    message: commitMsg,
    content: Buffer.from(content).toString("base64"), // GitHub requires base64
  });
}

export const createRepoAndPushCode = async (req, res) => {
  try {
    const { solution } = req.body; // 👈 full solution object (files + readme)
    const clerkUserId = req.auth?.userId; // ✅ FIXED

    if (!clerkUserId) {
      console.log("No clerkUserId found in request");
      return res.status(400).json({
        success: false,
        error: "Missing userId",
      });
    }

    console.log("Creating repo for user:", clerkUserId);

    // Get user from DB
    const user = await prisma.user.findUnique({
      where: { clerkUserId },
    });

    if (!user || !user.githubToken) {
      return res.status(404).json({
        success: false,
        error: "GitHub token not found for user",
      });
    }

    // Init Octokit
    const octokit = new Octokit({ auth: user.githubToken });

    // Generate repo name
    const repoName =
      slugify(solution.title || "architecture-ai-project", {
        lower: true,
        strict: true,
      }) + "-" + Date.now(); // ensure uniqueness

    // Create repo
    const { data: repo } = await octokit.repos.createForAuthenticatedUser({
      name: repoName,
      private: false,
      description: "Generated by ArchitectureAI 🚀",
    });

    const owner = repo.owner.login;

    // Upload solution files
    if (solution.files?.length > 0) {
      for (const file of solution.files) {
        await uploadFile(
          octokit,
          owner,
          repoName,
          file.path,
          file.content,
          `Add ${file.path}`
        );
      }
    }

    // Upload README if available
    if (solution.readme) {
      await uploadFile(
        octokit,
        owner,
        repoName,
        "README.md",
        solution.readme,
        "Add README"
      );
    }

    // Save repo URL to DB
    await prisma.user.update({
      where: { clerkUserId },
      data: {
        githubRepoUrls: {
          push: repo.html_url,
        },
      },
    });

    // ✅ Always return a proper response
    return res.status(200).json({
      success: true,
      message: "Repo created and solution pushed successfully 🚀",
      repoUrl: repo.html_url,
      repoName,
      owner,
    });
  } catch (error) {
    console.error("Error creating repo & pushing code:", error);
    return res.status(500).json({
      success: false,
      error: "Failed to create repo and push code",
      details: error.message,
    });
  }
};
